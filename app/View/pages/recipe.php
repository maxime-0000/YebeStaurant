    <div class="two-col">
        <section>
            <h2>Ingrédients</h2>
            <ul class="ingredients">
                <li>300 g de riz rond</li>
                <li>1,1 l de bouillon de légumes chaud</li>
                <li>1 poireau moyen, émincé</li>
                <li>120 g de petits pois</li>
                <li>1 échalote, finement hachée</li>
                <li>2 c. à soupe d’huile d’olive</li>
                <li>40 g de crème fraîche</li>
                <li>2 c. à soupe de graines de colza alimentaires</li>
                <li>Persil frais, sel et poivre</li>
            </ul>
        </section>

        <section>
            <h2>Préparation</h2>
            <ol class="steps">
                <li>
                    Faites chauffer le bouillon dans une casserole et gardez-le
                    chaud à feu doux.
                </li>
                <li>
                    Dans une sauteuse, faites revenir l’échalote et le poireau
                    avec l’huile pendant 5 minutes.
                </li>
                <li>
                    Ajoutez le riz et remuez une minute pour enrober les grains.
                </li>
                <li>
                    Versez le bouillon chaud louche après louche, en remuant.
                    Attendez que le liquide soit absorbé avant d’en ajouter.
                    Comptez environ 18 minutes, en goûtant pour vérifier la
                    cuisson.
                </li>
                <li>
                    Ajoutez les petits pois pour les 5 dernières minutes. Hors du
                    feu, incorporez la crème, salez et poivrez.
                </li>
                <li>
                    Faites dorer brièvement les graines à sec dans une petite
                    poêle, puis parsemez-en le plat avec le persil.
                </li>
            </ol>
        </section>
    </div>

    <h2>Présentation et résultat attendu</h2>
    <p>
        Servez aussitôt dans des assiettes creuses, avec un peu de persil et les
        graines toastées. Dans cette version imaginée, le riz est tendre et lié,
        le poireau fondant et les petits pois encore verts. Ajustez
        l’assaisonnement à votre goût.
    </p>

