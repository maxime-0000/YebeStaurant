<article class="content">
    <div class="callout">
        <p>
            <strong>À propos de ce lieu</strong>
            Ce restaurant n’existe pas dans le monde réel. Il n’a ni adresse, ni
            équipe, ni horaires. Il ne propose aucun service commercial.
        </p>
    </div>

    <h2>Un univers pour raconter une assiette</h2>
    <p>
        Nous avons imaginé une table chaleureuse, des matières simples et une
        cuisine généreuse. Le nom du restaurant associe le colza, culture
        présente dans le paysage beauceron, à une sonorité qui évoque le risotto.
        De cette association est né le colzotto.
    </p>

    <h2>Pourquoi le présenter comme un restaurant ?</h2>
    <p>
        Un site de restaurant donne un cadre facile à comprendre pour explorer
        une création culinaire : une page présente le lieu, une autre explique
        le plat, et une recette permet d’en suivre la préparation. Cette mise en
        scène sert le devoir ; elle ne décrit pas un établissement ouvert.
    </p>

    <h2>Un exercice de contenu et de référencement</h2>
    <p>
        Le projet cherche à répondre clairement aux questions des visiteurs, à
        organiser ses pages et à travailler l’expression « Le colzotto des
        champs » sans répétition artificielle.
    </p>

