<article class="content">
    <div class="callout">
        <p>
            <strong>Deux choses à distinguer</strong>
            La Beauce est un territoire réel. Le colzotto des champs est une
            création pédagogique, sans lien avec une tradition culinaire attestée.
        </p>
    </div>

    <h2>Quelques repères sur la Beauce</h2>
    <p>
        La Beauce est une région naturelle du Bassin parisien, connue pour ses
        paysages de plateau et ses grandes cultures. Dans sa présentation des
        paysages du Loiret, l’État décrit de grandes ouvertures visuelles
        associées aux cultures, un relief peu marqué et des bois qui ponctuent
        l’horizon. Les cultures céréalières, oléagineuses et protéagineuses font
        partie de ce paysage agricole.
    </p>
    <p>
        Ces repères décrivent un paysage et des activités agricoles réels. Ils
        ne permettent pas d’affirmer l’existence d’un plat appelé « colzotto »
        ni d’une tradition correspondante.
    </p>

    <h2>Comment ce paysage a inspiré le projet</h2>
    <p>
        Les tons de blé, de feuilles et de terre du site évoquent une campagne
        ouverte. L’idée du colza a inspiré le nom et quelques ingrédients de la
        recette imaginée. Ce rapprochement est un choix créatif, pas une origine
        historique ou gastronomique.
    </p>

