    <h1>Le colzotto des champs, une création inspirée de la Beauce</h1>
    <p class="lead">
        Le colzotto des champs est un plat fictif imaginé pour un devoir
        pédagogique : une sorte de risotto crémeux, associé au colza et aux
        légumes de saison.
    </p>
</section>

<article class="content">
    <div class="callout">
        <p>
            <strong>Le colzotto des champs est-il une véritable spécialité beauceronne ?</strong>
            Non. C’est une invention créée pour ce site. Il ne s’agit pas d’une
            tradition gastronomique documentée ni d’une recette transmise
            historiquement.
        </p>
    </div>

    <h2>Que trouve-t-on dans ce plat imaginé ?</h2>
    <p>
        Notre version associe du riz rond cuit progressivement dans un bouillon,
        des poireaux fondus, des petits pois, une pointe de crème et des graines
        de colza toastées. Les herbes fraîches apportent une note végétale. Cette
        composition est une proposition créative, pas une recette patrimoniale.
    </p>

    <h2>Une assiette dorée et généreuse</h2>
    <p>
        Servi dans un bol clair, le colzotto prend une teinte chaude grâce aux
        graines et au bouillon. La texture imaginée est fondante, avec quelques
        légumes qui gardent leur forme. Le résultat attendu est un plat doux,
        nourrissant et simple à partager.
    </p>

    <div class="two-col">
